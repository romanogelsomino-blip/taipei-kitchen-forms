#!/usr/bin/env node
/**
 * Generate frontend/config.js for an environment from .env.
 *
 * Usage: node scripts/write-frontend-config.js <staging|production>
 *
 * The browser has no environment to read from — the pages are static files on a CDN, with
 * no process behind them. So the Web App URL has to be baked into a file at build time.
 * This script is the only thing that writes it: from .env locally, from the matching
 * GitHub secret in CI (see .github/workflows/deploy.yml). The file is gitignored, so no
 * endpoint URL is ever committed and a form cannot inherit the wrong environment's backend.
 *
 * Nothing here is secret. The Web App URL is public — it is printed on QR codes and visible
 * in view-source. The point is a single source of truth, not confidentiality.
 */

const fs = require('fs');
const path = require('path');
const { readPrefix, requireKeys } = require('./env');

const { environment, prefix } = readPrefix(
  process.argv[2],
  'Usage: node scripts/write-frontend-config.js <staging|production>'
);

const { WEB_APP_URL: webAppUrl } = requireKeys(prefix, ['WEB_APP_URL']);

const target = path.join(__dirname, '..', 'frontend', 'config.js');
const contents = `// Generated by scripts/write-frontend-config.js — do not edit, do not commit.
window.APP_CONFIG = ${JSON.stringify({ environment, webAppUrl }, null, 2)};
`;

fs.writeFileSync(target, contents);

console.log(`frontend/config.js -> ${environment.toUpperCase()} (${webAppUrl})`);
