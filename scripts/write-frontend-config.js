#!/usr/bin/env node
/**
 * Generate frontend/config.js pointing at the staging backend, for a local `npm run serve`.
 *
 * Usage: node scripts/write-frontend-config.js
 *
 * The browser has no environment to read from — the pages are static files on a CDN, with
 * no process behind them. So the Web App URL has to be baked into a file at build time: here
 * from .env for a local run, by the deploy workflow from the matching secret in CI. The file
 * is gitignored, so no endpoint URL is ever committed and a form cannot inherit the wrong
 * environment's backend.
 *
 * Staging only. A local page never needs to point at production: the production dashboard
 * is a URL, and a local form pointed at it would write real rows.
 *
 * Nothing here is secret. The Web App URL is public — it is in the QR codes and visible in
 * view-source. The point is a single source of truth, not confidentiality.
 */

const fs = require('fs');
const path = require('path');
const { requireKeys } = require('./env');

const { WEB_APP_URL: webAppUrl } = requireKeys('STAGING', ['WEB_APP_URL']);

const target = path.join(__dirname, '..', 'frontend', 'config.js');
const contents = `// Generated by scripts/write-frontend-config.js — do not edit, do not commit.
window.APP_CONFIG = ${JSON.stringify({ environment: 'staging', webAppUrl }, null, 2)};
`;

fs.writeFileSync(target, contents);

console.log(`frontend/config.js -> STAGING (${webAppUrl})`);
