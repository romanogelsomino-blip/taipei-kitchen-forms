#!/usr/bin/env node
/**
 * Assemble _site the way the deploy workflow publishes it: the production tree at the root
 * and the staging tree under /staging/, each with its own config.js.
 *
 * CI builds those two trees from the prod and dev branches. Locally there is only the working
 * copy, so both are the same files. The point is the layout: the environment banner and the
 * environment toggle both read the path and the config, and neither behaves correctly against
 * a single tree.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const site = path.join(root, '_site');

fs.rmSync(site, { recursive: true, force: true });

function copy(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copy(src, dst);
    else fs.copyFileSync(src, dst);
  }
}

for (const [tree, target] of [['', site], ['staging', path.join(site, 'staging')]]) {
  copy(path.join(root, 'frontend'), target);
  copy(path.join(root, 'data'), path.join(target, 'data'));
  void tree;
}

// Each tree declares its own environment, which is what the banner and the toggle read.
// Without a config.js the dashboard falls back to sample data and the banner reads UNKNOWN.
//
// The file is parsed rather than pattern-matched: it is generated by
// scripts/write-frontend-config.js as JSON, and editing it by hand risks ending up with two
// `environment` keys where the second quietly wins.
const configured = path.join(root, 'frontend', 'config.js');
if (fs.existsSync(configured)) {
  const source = fs.readFileSync(configured, 'utf8');
  const match = source.match(/window\.APP_CONFIG\s*=\s*(\{[\s\S]*?\})\s*;/);
  if (!match) {
    console.error('  frontend/config.js is not in the expected shape; regenerate it with npm run env');
    process.exit(1);
  }
  const base = JSON.parse(match[1]);
  const write = (file, environment) => fs.writeFileSync(file,
    '// Generated by scripts/site-build.js — do not edit, do not commit.\n' +
    'window.APP_CONFIG = ' + JSON.stringify({ ...base, environment }, null, 2) + ';\n');
  write(path.join(site, 'config.js'), 'production');
  write(path.join(site, 'staging', 'config.js'), 'staging');
  console.log('  config.js written for both trees, pointing at ' + base.webAppUrl);
} else {
  console.log('  no frontend/config.js; both trees run on sample data (run npm run env to point at staging)');
}

console.log('  production tree  _site/');
console.log('  staging tree     _site/staging/');
